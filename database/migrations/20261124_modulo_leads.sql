BEGIN;

CREATE TABLE IF NOT EXISTS public.leads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  cliente_id BIGINT REFERENCES public.clientes(id)
    ON DELETE SET NULL,

  propiedad_id BIGINT REFERENCES public.propiedades(id)
    ON DELETE SET NULL,

  agente_id BIGINT REFERENCES public.agentes(id)
    ON DELETE SET NULL,

  nombre_contacto TEXT NOT NULL,
  telefono TEXT NOT NULL,
  email TEXT,

  origen TEXT NOT NULL DEFAULT 'otro'
    CHECK (origen IN (
      'portal', 'web', 'whatsapp', 'facebook',
      'instagram', 'llamada', 'referido',
      'oficina', 'otro'
    )),

  origen_detalle TEXT,

  estado TEXT NOT NULL DEFAULT 'nuevo'
    CHECK (estado IN (
      'nuevo', 'contactado', 'calificado',
      'visita_programada', 'negociacion',
      'ganado', 'perdido', 'pausado'
    )),

  prioridad TEXT NOT NULL DEFAULT 'media'
    CHECK (prioridad IN ('baja', 'media', 'alta', 'urgente')),

  tipo_operacion TEXT
    CHECK (
      tipo_operacion IS NULL OR
      tipo_operacion IN ('venta', 'alquiler', 'anticretico')
    ),

  tipo_inmueble TEXT,
  departamento TEXT,
  ciudad TEXT,
  zona TEXT,

  presupuesto_min NUMERIC,
  presupuesto_max NUMERIC,

  moneda TEXT NOT NULL DEFAULT 'USD'
    CHECK (moneda IN ('BOB', 'USD')),

  mensaje TEXT,
  motivo_perdida TEXT,

  puntuacion_ia INTEGER
    CHECK (
      puntuacion_ia IS NULL OR
      puntuacion_ia BETWEEN 0 AND 100
    ),

  recomendacion_ia TEXT,
  analizado_ia_en TIMESTAMPTZ,

  ultimo_contacto_en TIMESTAMPTZ,
  proximo_seguimiento_en TIMESTAMPTZ,
  convertido_en TIMESTAMPTZ,

  creado_por_tipo TEXT NOT NULL DEFAULT 'admin'
    CHECK (creado_por_tipo IN ('admin', 'agente', 'sistema')),

  creado_por_agente_id BIGINT
    REFERENCES public.agentes(id) ON DELETE SET NULL,

  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT leads_nombre_check
    CHECK (char_length(btrim(nombre_contacto)) BETWEEN 2 AND 150),

  CONSTRAINT leads_telefono_check
    CHECK (telefono ~ '^\+?[0-9\s().-]{7,25}$'),

  CONSTRAINT leads_presupuesto_check
    CHECK (
      (presupuesto_min IS NULL OR presupuesto_min >= 0)
      AND
      (presupuesto_max IS NULL OR presupuesto_max >= 0)
      AND
      (
        presupuesto_min IS NULL OR
        presupuesto_max IS NULL OR
        presupuesto_max >= presupuesto_min
      )
    )
);

CREATE TABLE IF NOT EXISTS public.lead_actividades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  lead_id BIGINT NOT NULL
    REFERENCES public.leads(id) ON DELETE CASCADE,

  tipo TEXT NOT NULL
    CHECK (tipo IN (
      'nota', 'llamada', 'whatsapp', 'correo',
      'reunion', 'visita', 'tarea',
      'cambio_estado', 'otro'
    )),

  titulo TEXT NOT NULL,
  descripcion TEXT,

  estado TEXT NOT NULL DEFAULT 'completada'
    CHECK (estado IN ('pendiente', 'completada', 'cancelada')),

  programado_en TIMESTAMPTZ,
  completado_en TIMESTAMPTZ,

  creado_por_tipo TEXT NOT NULL
    CHECK (creado_por_tipo IN ('admin', 'agente', 'sistema')),

  creado_por_agente_id BIGINT
    REFERENCES public.agentes(id) ON DELETE SET NULL,

  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT lead_actividades_titulo_check
    CHECK (char_length(btrim(titulo)) BETWEEN 2 AND 160)
);

CREATE TABLE IF NOT EXISTS public.lead_asignaciones_historial (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  lead_id BIGINT NOT NULL
    REFERENCES public.leads(id) ON DELETE CASCADE,

  agente_anterior_id BIGINT
    REFERENCES public.agentes(id) ON DELETE SET NULL,

  agente_nuevo_id BIGINT
    REFERENCES public.agentes(id) ON DELETE SET NULL,

  actor_tipo TEXT NOT NULL
    CHECK (actor_tipo IN ('admin', 'agente', 'sistema')),

  actor_agente_id BIGINT
    REFERENCES public.agentes(id) ON DELETE SET NULL,

  observacion TEXT,

  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS leads_agente_estado_idx
  ON public.leads (agente_id, estado, prioridad);

CREATE INDEX IF NOT EXISTS leads_cliente_idx
  ON public.leads (cliente_id);

CREATE INDEX IF NOT EXISTS leads_propiedad_idx
  ON public.leads (propiedad_id);

CREATE INDEX IF NOT EXISTS leads_estado_idx
  ON public.leads (estado);

CREATE INDEX IF NOT EXISTS leads_creado_idx
  ON public.leads (creado_en DESC);

CREATE INDEX IF NOT EXISTS leads_seguimiento_idx
  ON public.leads (proximo_seguimiento_en)
  WHERE proximo_seguimiento_en IS NOT NULL;

CREATE INDEX IF NOT EXISTS lead_actividades_lead_idx
  ON public.lead_actividades (lead_id, creado_en DESC);

CREATE INDEX IF NOT EXISTS lead_actividades_pendientes_idx
  ON public.lead_actividades (programado_en)
  WHERE estado = 'pendiente';

CREATE INDEX IF NOT EXISTS lead_asignaciones_historial_idx
  ON public.lead_asignaciones_historial (lead_id, creado_en DESC);

COMMENT ON TABLE public.leads IS
  'Oportunidades comerciales y prospectos inmobiliarios.';

COMMENT ON TABLE public.lead_actividades IS
  'Historial de comunicaciones, tareas y seguimientos de leads.';

COMMENT ON TABLE public.lead_asignaciones_historial IS
  'Auditoria de asignaciones y reasignaciones de leads.';

COMMIT;
