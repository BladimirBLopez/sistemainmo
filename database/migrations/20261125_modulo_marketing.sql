BEGIN;

CREATE TABLE IF NOT EXISTS public.marketing_campanas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  descripcion TEXT,
  objetivo TEXT NOT NULL DEFAULT 'captacion'
    CHECK (objetivo IN (
      'captacion', 'trafico', 'reconocimiento',
      'interaccion', 'ventas', 'otro'
    )),
  tipo TEXT NOT NULL DEFAULT 'paga'
    CHECK (tipo IN ('paga', 'organica', 'mixta')),
  estado TEXT NOT NULL DEFAULT 'borrador'
    CHECK (estado IN (
      'borrador', 'programada', 'activa',
      'pausada', 'finalizada', 'cancelada'
    )),
  presupuesto NUMERIC(14,2) NOT NULL DEFAULT 0
    CHECK (presupuesto >= 0),
  moneda TEXT NOT NULL DEFAULT 'BOB'
    CHECK (moneda IN ('BOB', 'USD')),
  fecha_inicio DATE,
  fecha_fin DATE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT marketing_campana_nombre_check
    CHECK (char_length(btrim(nombre)) BETWEEN 3 AND 160),

  CONSTRAINT marketing_campana_fechas_check
    CHECK (
      fecha_fin IS NULL OR fecha_inicio IS NULL
      OR fecha_fin >= fecha_inicio
    )
);

CREATE TABLE IF NOT EXISTS public.marketing_campana_canales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campana_id BIGINT NOT NULL
    REFERENCES public.marketing_campanas(id) ON DELETE CASCADE,
  plataforma TEXT NOT NULL
    CHECK (plataforma IN (
      'facebook', 'instagram', 'google',
      'tiktok', 'whatsapp', 'portal', 'otro'
    )),
  id_externo TEXT,
  url_externa TEXT,
  estado TEXT NOT NULL DEFAULT 'activo'
    CHECK (estado IN ('activo', 'pausado', 'finalizado')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.marketing_gastos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campana_id BIGINT
    REFERENCES public.marketing_campanas(id) ON DELETE RESTRICT,
  plataforma TEXT
    CHECK (
      plataforma IS NULL OR plataforma IN (
        'facebook', 'instagram', 'google',
        'tiktok', 'whatsapp', 'portal', 'otro'
      )
    ),
  fecha DATE NOT NULL DEFAULT CURRENT_DATE,
  categoria TEXT NOT NULL
    CHECK (categoria IN (
      'publicidad', 'diseno', 'produccion',
      'impresion', 'herramientas', 'otros'
    )),
  concepto TEXT NOT NULL,
  monto NUMERIC(14,2) NOT NULL CHECK (monto >= 0),
  moneda TEXT NOT NULL DEFAULT 'BOB'
    CHECK (moneda IN ('BOB', 'USD')),
  comprobante_url TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT marketing_gasto_concepto_check
    CHECK (char_length(btrim(concepto)) BETWEEN 2 AND 180)
);

CREATE TABLE IF NOT EXISTS public.marketing_contenidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campana_id BIGINT
    REFERENCES public.marketing_campanas(id) ON DELETE SET NULL,
  titulo TEXT NOT NULL,
  plataforma TEXT NOT NULL
    CHECK (plataforma IN (
      'facebook', 'instagram', 'google',
      'tiktok', 'whatsapp', 'portal', 'otro'
    )),
  formato TEXT NOT NULL DEFAULT 'post'
    CHECK (formato IN (
      'post', 'historia', 'reel',
      'video', 'carrusel', 'anuncio', 'otro'
    )),
  texto_publicacion TEXT,
  fecha_programada TIMESTAMPTZ,
  estado TEXT NOT NULL DEFAULT 'idea'
    CHECK (estado IN (
      'idea', 'pendiente', 'programado',
      'publicado', 'cancelado'
    )),
  url_publicacion TEXT,
  recurso_url TEXT,
  publicado_en TIMESTAMPTZ,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT marketing_contenido_titulo_check
    CHECK (char_length(btrim(titulo)) BETWEEN 2 AND 180)
);

CREATE TABLE IF NOT EXISTS public.marketing_metricas_diarias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campana_id BIGINT NOT NULL
    REFERENCES public.marketing_campanas(id) ON DELETE CASCADE,
  fecha DATE NOT NULL,
  plataforma TEXT NOT NULL
    CHECK (plataforma IN (
      'facebook', 'instagram', 'google',
      'tiktok', 'whatsapp', 'portal', 'otro'
    )),
  alcance INTEGER NOT NULL DEFAULT 0 CHECK (alcance >= 0),
  impresiones INTEGER NOT NULL DEFAULT 0 CHECK (impresiones >= 0),
  clics INTEGER NOT NULL DEFAULT 0 CHECK (clics >= 0),
  interacciones INTEGER NOT NULL DEFAULT 0 CHECK (interacciones >= 0),
  mensajes INTEGER NOT NULL DEFAULT 0 CHECK (mensajes >= 0),
  leads_reportados INTEGER NOT NULL DEFAULT 0
    CHECK (leads_reportados >= 0),
  conversiones_reportadas INTEGER NOT NULL DEFAULT 0
    CHECK (conversiones_reportadas >= 0),
  gasto_reportado NUMERIC(14,2) NOT NULL DEFAULT 0
    CHECK (gasto_reportado >= 0),
  moneda TEXT NOT NULL DEFAULT 'BOB'
    CHECK (moneda IN ('BOB', 'USD')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT marketing_metricas_diarias_unicas
    UNIQUE (campana_id, fecha, plataforma)
);

CREATE TABLE IF NOT EXISTS public.lead_captacion_limites (
  ip_hash TEXT PRIMARY KEY
    CHECK (ip_hash ~ '^[0-9a-f]{64}$'),
  intentos INTEGER NOT NULL DEFAULT 0
    CHECK (intentos >= 0),
  ventana_inicio TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  bloqueado_hasta TIMESTAMPTZ,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.leads
  ADD COLUMN IF NOT EXISTS campana_id BIGINT,
  ADD COLUMN IF NOT EXISTS utm_source VARCHAR(200),
  ADD COLUMN IF NOT EXISTS utm_medium VARCHAR(200),
  ADD COLUMN IF NOT EXISTS utm_campaign VARCHAR(200),
  ADD COLUMN IF NOT EXISTS utm_content VARCHAR(200),
  ADD COLUMN IF NOT EXISTS utm_term VARCHAR(200),
  ADD COLUMN IF NOT EXISTS pagina_origen VARCHAR(1000),
  ADD COLUMN IF NOT EXISTS referencia_origen VARCHAR(1000);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'leads_marketing_campana_fk'
      AND conrelid = 'public.leads'::regclass
  ) THEN
    ALTER TABLE public.leads
      ADD CONSTRAINT leads_marketing_campana_fk
      FOREIGN KEY (campana_id)
      REFERENCES public.marketing_campanas(id)
      ON DELETE SET NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS marketing_campanas_estado_idx
  ON public.marketing_campanas (estado, fecha_inicio);

CREATE INDEX IF NOT EXISTS marketing_canales_campana_idx
  ON public.marketing_campana_canales (campana_id);

DROP INDEX IF EXISTS public.marketing_canales_externo_idx;

CREATE UNIQUE INDEX marketing_canales_externo_idx
  ON public.marketing_campana_canales (campana_id, plataforma, id_externo)
  WHERE id_externo IS NOT NULL AND btrim(id_externo) <> '';

CREATE INDEX IF NOT EXISTS marketing_gastos_fecha_idx
  ON public.marketing_gastos (fecha DESC);

CREATE INDEX IF NOT EXISTS marketing_gastos_campana_idx
  ON public.marketing_gastos (campana_id, fecha DESC);

CREATE INDEX IF NOT EXISTS marketing_contenidos_agenda_idx
  ON public.marketing_contenidos (estado, fecha_programada);

CREATE INDEX IF NOT EXISTS marketing_metricas_campana_idx
  ON public.marketing_metricas_diarias (campana_id, fecha DESC);

CREATE INDEX IF NOT EXISTS leads_marketing_campana_idx
  ON public.leads (campana_id, creado_en DESC)
  WHERE campana_id IS NOT NULL;

COMMENT ON TABLE public.marketing_campanas IS
  'Campañas de marketing de la empresa inmobiliaria.';

COMMENT ON TABLE public.marketing_gastos IS
  'Registro de gastos y presupuesto ejecutado de marketing.';

COMMENT ON TABLE public.marketing_contenidos IS
  'Calendario y control de contenidos y publicaciones.';

COMMENT ON TABLE public.marketing_metricas_diarias IS
  'Indicadores diarios reportados por plataforma.';

COMMENT ON TABLE public.lead_captacion_limites IS
  'Control de frecuencia de solicitudes públicas de captación.';

COMMIT;
